export function getBlockDef(id: BlockType): BlockDef {
  return BLOCK_DEFS[id] || BLOCK_DEFS[BlockType.STONE];
}

export function isBlockSolid(id: BlockType): boolean {
  if (id === BlockType.AIR || id === BlockType.WATER || id === BlockType.LAVA || id === BlockType.TORCH || id === BlockType.ROSE || id === BlockType.DANDELION) {
    return false;
  }
  return true;
}

export function isBlockTransparent(id: BlockType): boolean {
  if (id === BlockType.AIR) return true;
  const def = BLOCK_DEFS[id];
  return !!def?.isTransparent;
}
